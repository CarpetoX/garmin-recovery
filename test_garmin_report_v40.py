class V40ReportTests(unittest.TestCase):
    def test_realistic_complete_report(self):
        ledger, cid = fixture()
        output, info = render(ledger, cid)
        for expected in ("V4.0", "88/100", "74/100", "74.2 lpm", "66 ms",
                         "11", "30,465", "1457.7", "9", "entrega a ChatGPT"):
            # Thousand separators are intentionally not generated by the renderer.
            if expected == "30,465":
                expected = "30465"
            self.assertIn(expected, output)
        self.assertEqual(info["recovery_state"], "assessed")
        self.assertTrue(info["sleep_confirmed"])
        self.assertTrue(info["chart_complete"])

    def test_deterministic(self):
        ledger, cid = fixture()
        self.assertEqual(render(ledger, cid), render(copy.deepcopy(ledger), cid))

    def test_only_certified_snapshot(self):
        ledger, cid = fixture()
        ledger["cycles"][0]["snapshot"]["recovery_assessment"]["score"] = 99
        with self.assertRaises(SnapshotError):
            render(ledger, cid)

    def test_provenance_mismatch_fails_closed(self):
        ledger, cid = fixture()
        ledger["cycles"][0]["source_generated_at"] = {"fake": "now"}
        with self.assertRaises(SnapshotError):
            render(ledger, cid)

    def test_wrong_cycle_state_fails_closed(self):
        ledger, cid = fixture()
        ledger["cycles"][0]["state"] = "pending"
        with self.assertRaises(SnapshotError):
            render(ledger, cid)

    def test_unsafe_identifier_rejected(self):
        ledger, cid = fixture()
        for bad in ("../escape", "2026-10-12-2245/other", "2026-10-12-2245\nX"):
            with self.subTest(bad=bad), self.assertRaises(SnapshotError):
                render(ledger, bad)

    def test_missing_chart_is_explicit_no_invention(self):
        ledger, cid = fixture(complete=False)
        output, info = render(ledger, cid)
        self.assertFalse(info["chart_complete"])
        self.assertIn("crossfit_chart_unavailable", info["warning_codes"])
        self.assertIn("No se reconstruye", output)

    def test_sleep_pending_does_not_recycle_old_sleep(self):
        ledger, cid = fixture(confirmed=False)
        output, info = render(ledger, cid)
        self.assertFalse(info["sleep_confirmed"])
        self.assertIn("Sueño pendiente", output)
        self.assertIn("Pendiente", output)
        self.assertNotIn("**7.23 h**", output)
        self.assertIn("| Recuperación fisiológica (modelo local) | Pendiente |", output)

    def test_stale_wellness_is_not_treated_as_current(self):
        ledger, cid = fixture()
        ledger['cycles'][0]['snapshot']['recovery_assessment']['current']['date'] = '2026-10-11'
        ledger['cycles'][0]['snapshot_sha256'] = digest(ledger['cycles'][0]['snapshot'])
        output, info = render(ledger, cid)
        self.assertFalse(info['sleep_confirmed'])
        self.assertIn('recovery_current_date_unverified', info['warning_codes'])
        self.assertIn('| Recuperación fisiológica (modelo local) | Pendiente |', output)

    def test_stale_heart_rate_is_not_treated_as_today(self):
        ledger, cid = fixture()
        ledger['cycles'][0]['snapshot']['garmin']['heart_rate_today']['date'] = '2026-10-11'
        ledger['cycles'][0]['snapshot_sha256'] = digest(ledger['cycles'][0]['snapshot'])
        output, info = render(ledger, cid)
        self.assertIn('heart_rate_today_date_unverified', info['warning_codes'])
        self.assertIn('| FC diurna | No disponible |', output)

    def test_partial_day_context_preserved(self):
        ledger, cid = fixture()
        text, info = render(ledger, cid)
        self.assertIn("día parcial", text)
        self.assertIn("daytime_hr_partial", info["warning_codes"])

    def test_unverified_live_not_represented_as_live(self):
        ledger, cid = fixture()
        ledger["cycles"][0]["snapshot"]["live_sensor_quality"] = {}
        ledger["cycles"][0]["snapshot_sha256"] = digest(ledger["cycles"][0]["snapshot"])
        output, _ = render(ledger, cid)
        self.assertIn("hora de medición reciente no confirmada", output)

    def test_immutable_write_and_idempotence(self):
        ledger, cid = fixture()
        with TemporaryDirectory() as tmp:
            a = publish(ledger, cid, tmp, True)
            b = publish(ledger, cid, tmp, True)
            self.assertEqual(a["state"], "published_local")
            self.assertEqual(b["state"], "already_present")
            self.assertEqual(len(list(Path(tmp).glob("*.md"))), 1)
            self.assertEqual(len(list(Path(tmp).glob("*.manifest.json"))), 1)
            man = json.loads(next(Path(tmp).glob("*.manifest.json")).read_text())
            self.assertEqual(man["report_sha256"], a["report_sha256"])
            self.assertEqual(man["delivery"], "unverified_no_chatgpt_receipt")

    def test_dry_run_no_side_effects(self):
        ledger, cid = fixture()
        with TemporaryDirectory() as tmp:
            a = publish(ledger, cid, Path(tmp) / "not-created", False)
            self.assertEqual(a["state"], "dry_run")
            self.assertFalse((Path(tmp) / "not-created").exists())

    def test_conflicting_report_refuses_overwrite(self):
        ledger, cid = fixture()
        with TemporaryDirectory() as tmp:
            a = publish(ledger, cid, tmp, True)
            md = Path(tmp) / a["report_file"]
            md.write_text("user edited report", encoding="utf-8")
            with self.assertRaises(SnapshotError):
                publish(ledger, cid, tmp, True)
            self.assertEqual(md.read_text(), "user edited report")

    def test_conflicting_manifest_refuses_overwrite(self):
        ledger, cid = fixture()
        with TemporaryDirectory() as tmp:
            a = publish(ledger, cid, tmp, True)
            md = Path(tmp) / a["report_file"]
            man = Path(tmp) / a["manifest_file"]
            man.write_text("tampered", encoding="utf-8")
            before = md.read_bytes()
            with self.assertRaises(SnapshotError):
                publish(ledger, cid, tmp, True)
            self.assertEqual(before, md.read_bytes())

    def test_latest_does_not_choose_legacy(self):
        ledger, cid = fixture()
        ledger["cycles"].insert(0, {"cycle_id": "2026-10-09-1645",
                                     "state": "data_ready", "ready_at": "2026-10-09T16:55:00+02:00"})
        self.assertEqual(latest_id(ledger), cid)

    def test_latest_fails_not_fall_back_when_invalid(self):
        ledger, cid = fixture()
        ledger["cycles"][-1]["snapshot_sha256"] = "bad"
        with self.assertRaises(SnapshotError):
            render(ledger, latest_id(ledger))

    def test_no_assumption_about_activities(self):
        ledger, cid = fixture()
        output, _ = render(ledger, cid)
        self.assertIn("no implica necesariamente descanso", output)

    def test_real_ledger_latest_when_present(self):
        path = Path("report_cycles.json")
        if not path.is_file():
            self.skipTest("Real ledger not packaged with offline tests")
        ledger = json.loads(path.read_text(encoding="utf-8"))
        # The newest slot must work even as the ledger grows in future cycles.
        cid = latest_id(ledger)
        report, info = render(ledger, cid)
        self.assertEqual(info["cycle_id"], cid)
        self.assertIn("SHA-256", report)
        self.assertEqual(info["delivery"], "unverified_no_chatgpt_receipt")


if __name__ == "__main__":
    unittest.main()
